function populateSelectFromMap(selectEl, mapObj, includeCustomOption) {
  if (!selectEl || !mapObj) return;
  const current = selectEl.value;
  selectEl.replaceChildren();
  Object.keys(mapObj).forEach((key) => {
    const opt = document.createElement("option");
    opt.value = key;
    const item = mapObj[key];
    opt.textContent = typeof item === "string" ? item : item.label;
    selectEl.appendChild(opt);
  });
  if (includeCustomOption) {
    const customOpt = document.createElement("option");
    customOpt.value = "custom";
    customOpt.textContent = "Custom Warna Sendiri";
    selectEl.appendChild(customOpt);
  }
  if (current && Array.from(selectEl.options).some((o) => o.value === current)) {
    selectEl.value = current;
  }
}

function loadDynamicFonts(headingFont, bodyFont) {
  const pairings = Object.values(window.NAOZI_THEMES.fontPairings);
  const matched = pairings.find(
    (p) => p.heading === headingFont && p.body === bodyFont
  ) || pairings.find((p) => p.heading === headingFont || p.body === bodyFont);

  let fontUrl = matched ? matched.googleUrl : "";
  if (!fontUrl && (headingFont || bodyFont)) {
    const families = [headingFont, bodyFont]
      .filter(Boolean)
      .map((f) => `family=${encodeURIComponent(f)}:wght@400;600;700`);
    if (families.length > 0) {
      fontUrl = `https://fonts.googleapis.com/css2?${families.join("&")}&display=swap`;
    }
  }

  if (fontUrl) {
    let link = document.getElementById("dynamic-theme-fonts");
    if (!link) {
      link = document.createElement("link");
      link.id = "dynamic-theme-fonts";
      link.rel = "stylesheet";
      document.head.appendChild(link);
    }
    if (link.href !== fontUrl) {
      link.href = fontUrl;
    }
  }

  if (headingFont) {
    document.documentElement.style.setProperty("--font-heading", `"${headingFont}", cursive, serif`);
    document.documentElement.style.setProperty("--font-display", `"${headingFont}", "Cinzel", Georgia, serif`);
  }
  if (bodyFont) {
    document.documentElement.style.setProperty("--font-body", `"${bodyFont}", sans-serif`);
    document.documentElement.style.setProperty("--font-sans", `"${bodyFont}", -apple-system, BlinkMacSystemFont, sans-serif`);
  }
}

